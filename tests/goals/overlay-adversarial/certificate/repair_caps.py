#!/usr/bin/env python3
"""Generate the Lean case analysis bounding zlib's bit-length repair term by Fibonacci caps.

For every clamped bit-length histogram c (levels 1..7) with at most NMAX leaves, clamped Kraft
sum 128 + M (M >= 1) and at least M + 1 leaves at level 7, the repair loop of gen_bitlen
(repairIter 7 M c) lengthens the ranks r_1 .. r_M. Each rank r weighs at most
fibCap W d = (W - F(d)) / F(d + 1), d the r-th smallest clamped depth. This script checks
sum_j fibCap W d(r_j) <= ALPHA + W / BETA_DEN for every W <= 316 and writes:

  * one small lemma per histogram (ranks and depths by rfl, the inequality by omega);
  * a prefix tree of case-split lemmas (each splits c(k+1) by omega);
  * the root theorem repairExtra_cap<NMAX>.

Usage: repair_caps.py NMAX ALPHA BETA_DEN OUTDIR
The output is evidence-free: the Lean kernel checks every lemma.
"""
import os
import sys

F = [0, 1]
for _ in range(40):
    F.append(F[-1] + F[-2])
WMAX = 316
LEAVES_PER_MODULE = 60


def len_of_rank(c, r):
    cum = 0
    for j in range(16):
        cum += c[j] if j < len(c) else 0
        if r <= cum:
            return j
    return 15


def histograms(nmax):
    out = []

    def rec(b, c, n):
        if b == 7:
            s6 = sum(c[x] * 2 ** (7 - x) for x in range(1, 7))
            if s6 > 127:
                return
            for c7 in range(128 - s6 + 1, nmax - n + 1):
                out.append(tuple(c) + (c7,))
            return
        for x in range(0, nmax - n + 1):
            if sum(c[y] * 2 ** (7 - y) for y in range(1, b)) + x * 2 ** (7 - b) > 127:
                break
            c[b] = x
            rec(b + 1, c, n + x)
        c[b] = 0

    rec(1, [0] * 7, 0)
    return out


def repair(c):
    """The ranks of repairExtra 7 w M c, as repairStep computes them."""
    s6 = sum(c[x] * 2 ** (7 - x) for x in range(1, 7))
    m = s6 + c[7] - 128
    cc = list(c)
    ranks = []
    for _ in range(m):
        b = 6
        while b > 0 and cc[b] == 0:
            b -= 1
        ranks.append(sum(cc[: b + 1]))
        cc[b] = max(cc[b] - 1, 0)
        cc[b + 1] += 2
        cc[7] = max(cc[7] - 1, 0)
    return m, ranks


def cap(w, d):
    return (w - F[d]) // F[d + 1]


def name(prefix):
    return "_".join(str(x) for x in prefix)


def main():
    nmax, alpha, beta = int(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3])
    outdir = sys.argv[4]
    tag = f"RepairCap{nmax}"
    bound = f"{alpha} + W / {beta}" if beta else f"{alpha}"
    hs = histograms(nmax)
    worst = None
    for c in hs:
        m, ranks = repair(c)
        for w in range(WMAX + 1):
            lhs = sum(cap(w, len_of_rank(c, r)) for r in ranks)
            rhs = alpha + (w // beta if beta else 0)
            slack = rhs - lhs
            if worst is None or slack < worst[0]:
                worst = (slack, c, w)
            if slack < 0:
                sys.exit(f"bound fails: c={c} W={w} lhs={lhs} rhs={rhs}")
    print(f"{len(hs)} histograms, smallest slack {worst[0]} at c={worst[1]} W={worst[2]}", file=sys.stderr)

    ns = "Zlib.Trees.HuffmanAbstract"
    head = ("/-! Generated by tests/goals/overlay-adversarial/certificate/repair_caps.py "
            f"{nmax} {alpha} {beta}. Do not edit. -/\n\n")
    common = (f"namespace {ns}.{tag}\nset_option autoImplicit false\n\n")
    goal = f"repairExtra 7 w M c ≤ {bound}"
    args = ("(c w : Nat → Nat) (W N M : Nat) (shape : RepairShape c N M) (hN : N ≤ {n}) (hM : 1 ≤ M)\n"
            "    (caps : RankCaps c w W N) (hW : W ≤ {wmax})").format(n=nmax, wmax=WMAX)

    # leaves
    modules = []
    leaf_mod = {}
    for i in range(0, len(hs), LEAVES_PER_MODULE):
        chunk = hs[i:i + LEAVES_PER_MODULE]
        k = len(modules)
        lines = [f"import ZlibF.Math.HuffmanRepairCap\n\n", head, common]
        for c in chunk:
            m, ranks = repair(c)
            n = sum(c[1:])
            hyp = " ".join(f"(h{j} : c {j} = {c[j]})" for j in range(1, 8))
            lines.append(f"theorem leaf_{name(c[1:])} {args}\n    {hyp} :\n    {goal} := by\n")
            lines.append(f"  have eN : N = {n} := by have := shape.leaves; omega\n")
            lines.append(f"  have eM : M = {m} := by have := shape.kraft; omega\n")
            lines.append("  subst eN eM\n")
            lines.append("  have e := shape.eq_cv h1 h2 h3 h4 h5 h6 h7\n")
            lines.append("  subst e\n")
            for r in sorted(set(ranks)):
                d = len_of_rank(c, r)
                lines.append(f"  have r{r} : w {r} ≤ (W - {F[d]}) / {F[d + 1]} := caps {r} (by omega) (by omega)\n")
            total = "".join(f"w {r} + (" for r in ranks) + "0" + ")" * len(ranks)
            lines.append(f"  have ex : repairExtra 7 w {m} (cv [{', '.join(str(x) for x in c)}]) = {total} := rfl\n")
            lines.append("  omega\n\n")
            leaf_mod[c] = k
        lines.append(f"end {ns}.{tag}\n")
        modules.append((f"Leaf{k}", "".join(lines)))

    # prefix tree
    def children(prefix):
        k = len(prefix)
        return sorted(set(c[k + 1] for c in hs if tuple(c[1:k + 1]) == tuple(prefix)))

    imports = "".join(f"import ZlibF.Math.{tag}.Leaf{k}\n" for k in range(len(modules)))
    lines = [imports, "\n", head, common]
    order = []

    def walk(prefix):
        k = len(prefix)
        if k == 7:
            return
        for v in children(prefix):
            walk(prefix + [v])
        order.append(prefix)

    walk([])
    for prefix in order:
        k = len(prefix)
        hyp = " ".join(f"(h{j} : c {j} = {prefix[j - 1]})" for j in range(1, k + 1))
        nm = "node_" + name(prefix) if prefix else "root"
        lines.append(f"theorem {nm} {args}" + (f"\n    {hyp}" if hyp else "") + f" :\n    {goal} := by\n")
        lines.append("  have := shape.leaves; have := shape.kraft; have := shape.top\n")
        vs = children(prefix)
        disj = " ∨ ".join(f"c {k + 1} = {v}" for v in vs)
        hs_names = " ".join(f"h{j}" for j in range(1, k + 1))
        if len(vs) == 1:
            lines.append(f"  have hv : {disj} := by omega\n")
            pats = ["hv"]
        else:
            lines.append(f"  have hv : {disj} := by omega\n")
            lines.append("  rcases hv with " + " | ".join("hv" for _ in vs) + "\n")
        for v in vs:
            child = prefix + [v]
            if k + 1 == 7:
                cn = f"leaf_{name(child)}"
            else:
                cn = f"node_{name(child)}"
            bullet = "  · " if len(vs) > 1 else "  "
            lines.append(f"{bullet}exact {cn} c w W N M shape hN hM caps hW {hs_names} hv\n".replace("  hv", " hv"))
        lines.append("\n")
    lines.append(f"end {ns}.{tag}\n\nnamespace {ns}\n\n")
    lines.append(f"/-- **The repair term under the Fibonacci caps**, at most {nmax} leaves. -/\n")
    lines.append(f"theorem repairExtra_cap{nmax} {args} :\n    {goal} :=\n")
    lines.append(f"  {tag}.root c w W N M shape hN hM caps hW\n\nend {ns}\n")
    modules.append(("Tree", "".join(lines)))

    os.makedirs(os.path.join(outdir, tag), exist_ok=True)
    for mod, text in modules:
        with open(os.path.join(outdir, tag, mod + ".lean"), "w") as f:
            f.write(text)
    with open(os.path.join(outdir, tag + ".lean"), "w") as f:
        f.write(f"import ZlibF.Math.{tag}.Tree\n")


if __name__ == "__main__":
    main()
