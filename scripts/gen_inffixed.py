#!/usr/bin/env python3
"""Generate ZlibF/Zlib/inffixed.h.lean from inffixed.h of the verified source.

    python3 scripts/gen_inffixed.py <verified source directory> > ZlibF/Zlib/inffixed.h.lean

The entries are copied one by one, in order, from the C file.
"""
import re
import sys

text = open(sys.argv[1] + "/inffixed.h").read()
o = ["-- GENERATED by scripts/gen_inffixed.py from inffixed.h of the verified source. Do not edit.\n",
     "import ZlibF.Runtime.Schema\n\n",
     "/-!\n# inffixed.h: the fixed decoding tables\n\n`lenfix[512]` and `distfix[32]`, entry for entry as in the C header (they are not the output of\n`inflate_table`: four entries of `lenfix` differ, see `docs/proof/inftrees.md#c-correspondence-checks`).\n-/\n\n",
     "namespace Zlib.InffixedH\nopen C\n\n"]
for name, n in (("lenfix", 512), ("distfix", 32)):
    m = re.search(r"static const code %s\[(\d+)\] = \{(.*?)\n\};" % name, text, re.S)
    assert int(m.group(1)) == n
    ents = re.findall(r"\{(\d+),(\d+),(\d+)\}", m.group(2))
    assert len(ents) == n
    lines = []
    for i in range(0, n, 4):
        lines.append("    " + ", ".join("⟨%s, %s, %s⟩" % e for e in ents[i:i + 4]))
    o.append("/-- `static const code %s[%d]` -/\ndef %s : Array Code := #[\n%s]\n\n" % (name, n, name, ",\n".join(lines)))
o.append("end Zlib.InffixedH\n")
sys.stdout.write("".join(o))
