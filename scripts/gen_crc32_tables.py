#!/usr/bin/env python3
"""Generate ZlibF/Zlib/crc32.h.lean from crc32.h of the verified source.

    python3 scripts/gen_crc32_tables.py <verified source directory> > ZlibF/Zlib/crc32.h.lean

The live tables of the default build (W = 8, N = 5, little and big endian) are taken from the C
preprocessor's output for crc32.h (`gcc -E -P -DW=8 -DN=5`), so the values are copied, not computed.
"""
import re
import subprocess
import sys

src = sys.argv[1]
pp = subprocess.run(["gcc", "-E", "-P", "-DW=8", "-DN=5", "-Dlocal=", "-DFAR=", "-Dz_crc_t=unsigned",
                     "-Dz_word_t=unsigned long", "-x", "c", src + "/crc32.h"],
                    check=True, capture_output=True, text=True).stdout
tabs = {}
for m in re.finditer(r"const\s+[a-z_ ]+?\s+(\w+)\s*\[\s*(\d*)\s*\](\s*\[\s*256\s*\])?\s*=\s*\{(.*?)\};", pp, re.S):
    name, vals = m.group(1), [int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", m.group(4))]
    assert name not in tabs, name
    tabs[name] = vals

def row(vals, w):
    out = []
    for i in range(0, len(vals), 4):
        out.append("    " + ", ".join("0x%0*x" % (w, v) for v in vals[i:i + 4]))
    return ",\n".join(out)

def flat(name, ty, n, w, doc):
    v = tabs[name]; assert len(v) == n, (name, len(v))
    return f"/-- {doc} -/\ndef {name} : Array {ty} := #[\n{row(v, w)}]\n\n"

def braid(name, ty, w, doc):
    v = tabs[name]; assert len(v) == 8 * 256, (name, len(v))
    rows = ",\n".join("  #[\n" + row(v[256 * k:256 * k + 256], w) + "]" for k in range(8))
    return f"/-- {doc} -/\ndef {name} : Array (Array {ty}) := #[\n{rows}]\n\n"

o = ["-- GENERATED by scripts/gen_crc32_tables.py from crc32.h of the verified source. Do not edit.\n",
     "/-!\n# crc32.h: the tables of the default build\n\nW = 8 (`z_word_t` is 64 bits), N = 5, `z_crc_t` is 32 bits. The tables for the other values of W and N are\nnot live in this configuration. `crc_table` and `x2n_table` are also the content of the `Statics` fields of the\nsame name (`initStatics`); the others are only ever indexed, never addressed, and are plain constants.\n-/\n\n",
     "namespace Zlib.Crc32H\n\nset_option maxRecDepth 100000\n\n"]
o.append(flat("crc_table", "UInt32", 256, 8, "`crc_table[256]` (`z_crc_t`)"))
o.append(flat("crc_big_table", "UInt64", 256, 16, "`crc_big_table[256]` for `W == 8` (`z_word_t`)"))
o.append(braid("crc_braid_table", "UInt32", 8, "`crc_braid_table[8][256]` for `N == 5`, `W == 8`"))
o.append(braid("crc_braid_big_table", "UInt64", 16, "`crc_braid_big_table[8][256]` for `N == 5`, `W == 8`"))
o.append(flat("x2n_table", "UInt32", 32, 8, "`x2n_table[32]` (`z_crc_t`)"))
o.append("end Zlib.Crc32H\n")
sys.stdout.write("".join(o))
