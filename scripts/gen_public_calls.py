#!/usr/bin/env python3
"""Generate the typed public call catalogue from the reviewed entry-point inventory."""

import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "ZlibF/Spec/Public/Calls.lean"


def generate() -> str:
    rows = json.loads((ROOT / "tests/audit/public-api.json").read_text())["apis"]
    cases = []
    for row in rows:
        if row["scope"] != "lp64-linux":
            continue
        name = row["function"]
        text = (ROOT / row["source"]).read_text()
        match = re.search(r"^def\s+«?" + re.escape(name) + r"»?(?=\s|:|\()\s*(.*?)(?::=|\swhere)", text, re.M | re.S)
        if not match:
            raise ValueError(f"missing translated signature: {name}")
        signature = re.sub(r"\s+", " ", match[1]).strip()
        args, result = signature.rsplit(" : ", 1) if " : " in signature else ("", signature.removeprefix(": "))
        arguments = []
        for binder in re.findall(r"\(([^()]*)\)", args):
            names, _ = binder.split(":", 1)
            arguments.extend(names.split())
        if result.startswith(("M ", "G ")):
            monad, returned = result.split(" ", 1)
        else:
            monad, returned = "pure", result
        cases.append((row, args, arguments, monad, returned))
    imports = sorted(set(row["source"] for row, *_ in cases))
    imports = ["import ZlibF.Zlib.«" + Path(p).name.removesuffix(".lean") + "»" for p in imports]
    lines = imports + ["", "/-!", "# Concrete public calls", "",
        "Generated by `scripts/gen_public_calls.py`. The inventory fixes the exported entry names.",
        "Arguments and results retain the types of the actual translations. Every constructor runs",
        "that entry directly. No replaceable execution relation or callee contract occurs here.",
        "The shared state includes the runtime heap and, for gz operations, the file-system model.",
        "This catalogue defines execution, not the permitted caller domain or the final contract.",
        "-/", "", "namespace ZlibF.Spec.Public", "open C Zlib.GzFs Zlib.Infback", "",
        "/-- Public entry calls for the default LP64 Linux build. Macro aliases use their C entries. -/",
        "inductive Call where"]
    for row, args, _, _, _ in cases:
        lines.append("  | " + row["function"] + (" " + args if args else ""))
    lines += ["", "/-- The result type of the selected public entry. -/", "def Call.Result : Call → Type"]
    for row, _, args, _, returned in cases:
        lines.append("  | ." + row["function"] + (" " + " ".join("_" for _ in args) if args else "") + " => " + returned)
    lines += ["", "/-- Lift a heap computation without changing or hiding its outcome. -/",
        "def heapCall {α : Type} (program : C.M α) : G α := fun fs h =>",
        "  match program h with", "  | .error fault => .error fault",
        "  | .ok (value, after) => .ok ((value, fs), after)", "",
        "/-- Execute the actual translated entry with every argument and result preserved. -/",
        "def Call.execute : (call : Call) → G call.Result"]
    for row, _, args, monad, _ in cases:
        application = row["implementation"] + (" " + " ".join(args) if args else "")
        body = "heapCall (" + application + ")" if monad == "M" else "pure (" + application + ")" if monad == "pure" else application
        lines.append("  | ." + row["function"] + (" " + " ".join(args) if args else "") + " => " + body)
    lines += ["", "/-- A concrete total-correctness schema. Final goals must fix `pre` and `post` in",
        "reviewed definitions and establish their domain from init. This schema is not itself",
        "a completed per-function contract. Successful execution is required explicitly. -/",
        "def Correct (call : Call) (pre : Heap → Fs → Prop)",
        "    (post : Heap → Fs → call.Result → Heap → Fs → Prop) : Prop :=",
        "  ∀ before fs, pre before fs → ∃ value after fs',",
        "    call.execute fs before = .ok ((value, fs'), after) ∧",
        "    post before fs value after fs'", "", "end ZlibF.Spec.Public", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not DEST.is_file() or DEST.read_text() != content:
            print("public call catalogue differs from the translated signatures", file=sys.stderr)
            return 1
        print("public call catalogue matches all 95 translated entries")
    else:
        DEST.parent.mkdir(parents=True, exist_ok=True)
        DEST.write_text(content)
    return 0


if __name__ == "__main__":
    sys.exit(main())
